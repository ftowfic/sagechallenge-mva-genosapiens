INDEX_SCHEMA = 'genosapiens.track2-vcf-selection-index/v5'
POLICY = 'exact-pass-sequence-and-scoped-structural/v4'
SMALL = re.compile(r'[ACGTN]+')


class SourceSelectionError(ValueError):
    """Static diagnostic; do not expose genomic rows or selected sample names."""


def require(ok, message='source selection input is incomplete or stale'):
    if not ok:
        raise SourceSelectionError(message)


def signature(path):
    path = Path(path)
    require(not any(p.is_symlink() for p in (path, *path.parents)))
    s = path.stat()
    return [s.st_dev, s.st_ino, s.st_size, s.st_mtime_ns, s.st_ctime_ns]


def code_binding():
    return sha256(canonical({p.name:sha256(p.read_bytes()) for p in (
        Path(__file__), Path(__file__).with_name('variant_normalization.py'),
        *(Path(__file__).with_name(name) for name in ('vcf_qc.py','track2_reference.py',
            'supplied_structural.py','track2_structural.py','allele_identity.py',
            'track2_exclusions.py','track2_vcf_evidence.py','vcf_contracts.py','vcf_context.py')))}))


def binding(scope, concordance, sample, reference_mapping, classification, evidence_origin, pid_phase_contract=None,
            *, prepared):
    _validate_concordance(concordance)
    require(bool(sample) and scope['schema'] == 'genosapiens.track2-diagnosis-scope/v1'
            and scope['reference_sha256'] == concordance.reference_manifest_sha256)
    require((classification, evidence_origin) in {('controlled','controlled_case'),
        ('public','public_source'),('public','independently_synthetic')})
    mapping = reference_mapping
    require(pid_phase_contract is None or pid_phase_contract.input_sha256==concordance.validated_input_sha256,
            'The PID contract belongs to another source.')
    require(mapping['schema'] == MAPPING_SCHEMA
        and mapping['source_role'] == concordance.reference_role
        and mapping['source_identity_id'] == concordance.reference_identity_id
        and mapping['scope_role'] == 'public_annotation_benchmark'
        and mapping['reference_sha256'] == scope['reference_sha256'],
        'required reference-role mapping is inconsistent')
    contig_map = mapping['contig_map']
    require(set(contig_map) == set(mapping['source_lengths']) and all(
        isinstance(k, str) and k and (v is None or isinstance(v, str) and v)
        for k, v in contig_map.items()), 'required source-contig mapping is absent')
    required = set(prepared.by_contig)
    require(required <= set(contig_map.values()), 'required scope-contig mapping is absent')
    for chrom, start, end, _ in prepared.rows:
        require(chrom in mapping['scope_lengths'] and end <= mapping['scope_lengths'][chrom]
            and all(mapping['source_lengths'][name] == mapping['scope_lengths'][chrom]
                    for name, target in contig_map.items() if target == chrom),
            'required scope-contig mapping is inconsistent')
    return {'source_sha256':concordance.validated_input_sha256, 'sample':sample,
        'reference_sha256':concordance.reference_manifest_sha256,
        'reference_identity_id':concordance.reference_identity_id,'reference_role':concordance.reference_role,
        'concordance_sha256':sha256(canonical(asdict(concordance))),
        'scope_sha256':sha256(canonical(scope)), 'contig_map':dict(sorted(contig_map.items())),
        'reference_mapping':mapping,
        'classification':classification,'evidence_origin':evidence_origin,
        'vcf_policy_sha256':VCF_POLICY_SHA256,'read_limits':asdict(concordance.read_limits),
        'reference_declarations':[asdict(r) for r in concordance.reference_declarations],
        'pid_contract_sha256':None if pid_phase_contract is None else pid_phase_contract.sha256,
        'selection_policy':POLICY,'code_sha256':code_binding()}


def intervals(scope):
    rows=[]
    for row in scope['intervals']:
        require(row['coordinate_system'] == 'zero_based_half_open' and row['assembly'] == 'GRCh38'
                and type(row['start']) is int and type(row['end']) is int and 0 <= row['start'] < row['end'])
        rows.append((row['chromosome'],row['start'],row['end'],row['gene_id']))
    require(rows and all(r[3] in scope['genes'] for r in rows))
    return sorted(set(rows))


@dataclass(frozen=True)
class PreparedIntervals:
    rows: tuple
    by_contig: dict
    structural_by_contig: dict


def prepare_intervals(scope):
    """Build contig groups once, preserving each gene and original interval."""
    rows=tuple(intervals(scope))
    sequence={};structural={}
    for chrom,start,end,gene in rows:
        sequence.setdefault(chrom,[]).append((start,end,gene))
    for row in scope['intervals']:
        structural.setdefault(row['chromosome'],[]).append(dict(row))
    # Exact disease alleles extend retrieval without assigning a missing gene.
    # They do not expand the structural observation scope.
    extra = []
    for row in scope.get('mapping_evidence', {}).get('known_alleles', {}).get('assertions', ()):
        allele = row['allele']
        require(allele['reference_sha256'] == scope['reference_sha256'])
        chrom = 'chrM' if allele['contig'] == 'MT' else 'chr' + allele['contig']
        start = allele['position'] - 1
        end = start + len(allele['reference'])
        extra.append((chrom, start, end, None))
        sequence.setdefault(chrom, []).append((start, end, None))
    rows = tuple(sorted(set((*rows, *extra)), key=lambda r: (r[0], r[1], r[2], r[3] or '')))
    return PreparedIntervals(rows,{k:tuple(v) for k,v in sequence.items()},
        {k:tuple(v) for k,v in structural.items()})


def normalize(record, bound, fetch):
    requested=0
    def limited(contig, position, length):
        nonlocal requested
        requested+=length
        require(requested<=4*1024*1024,'source normalization reference budget exceeded')
        return fetch(contig,position,length)
    return normalize_source_record(SourceSmallVariantRecord(record.record_number,record.contig,record.position,
        record.reference,record.alternates),input_sha256=bound['source_sha256'],
        reference_identity_id=bound['reference_identity_id'],reference_role=bound['reference_role'],fetch_reference=limited)


def geometry(record, normalized, contig_map):
    require(record.contig in contig_map, 'required source-contig mapping is absent')
    chrom=contig_map[record.contig]
    if chrom is None:
        return []
    spans={(chrom,record.position-1,record.position-1+len(record.reference))}
    # Source-event spans retain deletions beginning outside an interval. The
    # normalized span additionally retains repeat-shifted equivalent alleles.
    for allele in normalized.alleles:
        n=allele.normalized_allele
        if n is not None:
            spans.add((chrom,n.position-1,n.position-1+len(n.reference)))
    return sorted(spans)


def selected(record, normalized, scope_intervals, bound):
    require(record.filter_value == 'PASS', 'Scientific selection requires exact FILTER=PASS.')
    sample=next((s for s in record.sample_calls if s.sample_name==bound['sample']),None)
    require(sample is not None,'selected sample is absent')
    # Unknown genotypes retain candidate observations; explicit non-carriers do
    # not manufacture alleles. Multi-allelic calls keep original ALT numbering.
    tokens=re.split(r'[/|]',sample.genotype or '.')
    carried=None if '.' in tokens else {int(t) for t in tokens}
    rows=[]
    require(record.contig in bound['contig_map'], 'required source-contig mapping is absent')
    chrom=bound['contig_map'][record.contig]
    for allele in normalized.alleles:
        if carried is not None and allele.allele_number not in carried:
            continue
        if not SMALL.fullmatch(record.reference) or not SMALL.fullmatch(allele.alternate):
            continue
        spans=[(record.position-1,record.position-1+len(record.reference))]
        n=allele.normalized_allele
        if n is not None:spans.append((n.position-1,n.position-1+len(n.reference)))
        hits={g for start,end,g in scope_intervals.get(chrom,())
              if any(a<end and start<b for a,b in spans)}
        genes=sorted(g for g in hits if g is not None)
        if hits:
            # A failed reference lookup cannot become an accepted negative result.
            require(n is not None,'scoped allele normalization is unresolved')
            rows.append({'allele_id':allele.source_allele_id,'source_record_id':record.source_record_id,
                         'source_allele_id':allele.source_allele_id,'normalized_allele_id':n.normalized_allele_id,
                         'gene_ids':genes,'allele_number':allele.allele_number})
    return rows


def filter_exclusion(record):
    return {'source_record_id':record.source_record_id, 'record_number':record.record_number,
        'raw_line_sha256':record.raw_line_sha256, 'filter_value':record.filter_value,
        'alternate_count':len(record.alternates), 'reason':'filter_not_exact_pass'}


ACCOUNTING = ('quality_excluded','not_carried','outside_scope','sequence_scoped',
              'structural_review','unsupported_class','unresolved_structural','no_sequence_change')


def account_record(record, normalized, rows, observations, bound):
    """Partition every source ALT occurrence once, including unselected records."""
    result=Counter()
    if record.filter_value != 'PASS':
        result['quality_excluded']=len(record.alternates)
        return result
    selected_ids={r['allele_number'] for r in rows}
    structural={r['allele_number']:r['outcome'] for r in observations}
    sample=next(s for s in record.sample_calls if s.sample_name==bound['sample'])
    tokens=re.split(r'[/|]',sample.genotype or '.')
    carried=None if '.' in tokens else {int(t) for t in tokens}
    for number, alternate in enumerate(record.alternates,1):
        if carried is not None and number not in carried:
            outcome='not_carried'
        elif number in structural:
            outcome={'scoped':'structural_review','outside_scope':'outside_scope',
                'non_carrier':'not_carried','unsupported':'unsupported_class',
                'unresolved':'unresolved_structural'}[structural[number]]
        elif not SMALL.fullmatch(record.reference) or not SMALL.fullmatch(alternate):
            outcome='unsupported_class'
        elif alternate==record.reference:
            outcome='no_sequence_change'
        else:
            outcome='sequence_scoped' if number in selected_ids else 'outside_scope'
        result[outcome]+=1
    return result


def sequence_quality(record, sample, allele_number):
    """Apply shared ALT-specific QC, adding explicit missing-measurement states."""
    from genosapiens.vcf_qc import technical_flags_for, phase_reasons_for
    failures=list(technical_flags_for(record, sample, allele_number))
    missing=[]
    # Phase interpretation belongs to the genotype model. Retention flags
    # cannot turn sufficient standard GT evidence into failed sample quality.
    phase_reasons=set(phase_reasons_for(sample,allele_number))
    failures=[r for r in failures if r not in phase_reasons and r!='ad-dp-relationship-unresolved']
    if sample.ad_dp_state=='unresolved':
        missing.append('ad_dp_relationship_unresolved')
        failures=[r for r in failures if 'allele-balance-' not in r and 'alt-balance-' not in r]
    elif sample.ad_dp_state=='partial':
        missing.append('allelic_depths_partial')
    if record.filter_value != 'PASS': failures.append('filter_not_exact_pass')
    tokens=re.split(r'[/|]',sample.genotype or '.')
    if '.' in tokens:
        failures=[r for r in failures if r!='sample-genotype-uncallable']
    if sample.callable is not True or '.' in tokens: missing.append('complete_genotype_required')
    elif str(allele_number) not in tokens: failures.append('alternate_not_carried')
    if sample.genotype_quality is None: missing.append('genotype_quality_missing')
    if sample.depth is None: missing.append('depth_missing')
    balances=sample.alternate_allele_balance
    balance=balances[allele_number-1] if balances is not None and len(balances)>=allele_number else None
    if balance is None: missing.append('allele_balance_missing')
    # INFO diagnostics never supply sample depth, quality, or alternate balance.
    info={}
    if record.raw_line:
        for item in record.raw_line.split('\t')[7].split(';'):
            if item.startswith('ExcessHet='): info['ExcessHet']=item.split('=',1)[1]
    return {'policy':POLICY, 'source_record_id':record.source_record_id,
        'allele_number':allele_number, 'filter_value':record.filter_value,
        'genotype':sample.genotype, 'observed_ploidy':sample.ploidy,
        'genotype_quality':sample.genotype_quality, 'depth':sample.depth,
        'allele_depths':sample.allelic_depths, 'allele_balance':balance, 'diagnostics':info,
        'vcf_policy_sha256':sample.evidence_policy_sha256,'ad_dp_state':sample.ad_dp_state,
        'format_fields':[{**asdict(field),'state':field.state.value} for field in sample.format_fields],
        'phase_state':sample.phase_state.value,'phase_reasons':list(sample.phase_reasons),
        'phase_set':sample.phase_set,'pgt':sample.pgt,'pid':sample.pid,
        'pid_contract_sha256':sample.pid_contract_sha256,
        'state':'excluded' if failures else 'unresolved' if missing else 'accepted',
        'reasons':sorted(set(failures+missing)) or ['quality_requirements_satisfied']}


def replay_sequence_quality(call):
    """Validate retained measurements before replaying shared sample QC rules."""
    from types import SimpleNamespace
    from genosapiens.evidence_serialization import _plain
    from genosapiens.vcf_qc import FilterStatus, _technical_scopes
    fields=call.source.source_fields or {}
    if 'quality_alternate_count' not in fields or call.sample is None: return None
    sample=call.sample
    require(fields['filter_value']=='PASS','Quality source differs from selection.')
    scopes=_technical_scopes(FilterStatus.PASS,(sample,),fields['quality_alternate_count'])
    record=SimpleNamespace(sample_calls=(sample,),filter_value=fields['filter_value'],
        source_record_id=fields['source_record_id'],raw_line=None,
        alternates=(None,)*fields['quality_alternate_count'],
        **dict(zip(('technical_flags','alternate_technical_flags','sample_technical_flags',
                    'sample_alternate_technical_flags'),scopes)))
    result=sequence_quality(record,sample,fields['allele_number'])
    result['diagnostics']=dict(fields['automatic_quality']['diagnostics'])
    require(canonical(result)==canonical(_plain(fields['automatic_quality'])),'Quality assessment disagrees with source measurements.')
    return result


def build_selection_index(path, vcf_path, *, scope, concordance, sample, fetch_reference,
                          reference_mapping, classification, evidence_origin,
                          maximum_records=10000000, maximum_bytes=4*1024**3, deadline_seconds=3600,
                          pid_phase_contract=None):
    """One source pass creates a complete, immutable, normalization-aware index.

    Index construction is optional. Ordinary unindexed intake selects directly
    in one pass and does not create this source cache.
    """
    prepared=prepare_intervals(scope)
    bound=binding(scope,concordance,sample,reference_mapping,classification,evidence_origin,pid_phase_contract,prepared=prepared)
    from genosapiens.track2_structural import observe, source_context
    require(type(maximum_records) is int and maximum_records>0 and maximum_bytes>0 and 0<deadline_seconds<=3600)
    path=Path(path);path.mkdir(mode=0o700,exist_ok=False)
    database=path/'selection.sqlite';started=time.monotonic();deadline=started+deadline_seconds
    count=0; classes=Counter(); accounting=Counter()
    try:
        with closing(sqlite3.connect(database)) as db, db, iter_vcf_qc_records(vcf_path,concordance_report=concordance,
                max_header_bytes=concordance.read_limits.max_header_bytes,max_record_bytes=concordance.read_limits.max_record_bytes,
                pid_phase_contract=pid_phase_contract) as stream, ExclusionWriter(
                path/'filter-exclusions', binding=bound, source_records=concordance.total_records) as exclusions:
            database.chmod(0o600)
            require(sample in stream.header.sample_names,'selected sample is absent')
            header=asdict(stream.header)
            structural_context=source_context(stream.header)
            db.executescript('''CREATE TABLE records(ordinal INTEGER PRIMARY KEY,raw TEXT NOT NULL);
                CREATE TABLE spans(chrom TEXT,start INTEGER,end INTEGER,ordinal INTEGER);
                CREATE INDEX region ON spans(chrom,start,end);
                CREATE TABLE structural(ordinal INTEGER PRIMARY KEY,observations TEXT NOT NULL);
                CREATE TABLE completion(identity TEXT NOT NULL);''')
            for record in stream:
                count+=1
                classes.update(str(kind) for kind in record.variant_classes)
                require(count<=maximum_records and time.monotonic()<=deadline,
                        'source index construction incomplete: budget exceeded')
                if record.filter_value != 'PASS':
                    exclusions.append(filter_exclusion(record))
                    accounting.update(account_record(record,None,(),(),bound))
                    require(exclusions.bytes<=maximum_bytes,'source index size limit exceeded')
                    continue
                n=normalize(record,bound,fetch_reference)
                # An out-of-scope unresolvable indel might have shifted into the
                # scope. Completeness cannot be attested when normalization fails.
                require(all(a.normalized_allele is not None or not SMALL.fullmatch(a.alternate)
                            or a.alternate==record.reference for a in n.alleles),
                        'source index normalization coverage is incomplete')
                db.execute('INSERT INTO records VALUES (?,?)',(record.record_number,record.raw_line))
                db.executemany('INSERT INTO spans VALUES (?,?,?,?)',
                    [(*span,record.record_number) for span in geometry(record,n,bound['contig_map'])])
                observations=observe(record,structural_context,prepared.structural_by_contig,bound)
                accounting.update(account_record(record,n,selected(record,n,prepared.by_contig,bound),observations,bound))
                if observations:
                    db.execute('INSERT INTO structural VALUES (?,?)',
                        (record.record_number,canonical(observations).decode('ascii')))
                if count%1000==0:
                    db.commit();require(database.stat().st_size+exclusions.bytes<=maximum_bytes,'source index size limit exceeded')
            db.execute('INSERT INTO completion VALUES (?)',(sha256(canonical(bound)),))
            exclusion_artifact=exclusions.finish(source_records=count,source_alternates=sum(classes.values()))
        require(database.stat().st_size+exclusion_artifact['bytes']<=maximum_bytes,'source index size limit exceeded')
        digest=hashlib.sha256()
        with database.open('rb') as source:
            for chunk in iter(lambda:source.read(1024*1024),b''):digest.update(chunk)
        manifest={'schema':INDEX_SCHEMA,'binding':bound,'header':header,'record_count':count,
            'filter_exclusions':exclusion_artifact,
            'source_alternate_class_counts':dict(sorted(classes.items())),
            'source_accounting':{k:accounting[k] for k in ACCOUNTING},
            'source_signature':signature(vcf_path),'index_signature':signature(database),'index_sha256':digest.hexdigest()}
        raw=canonical(manifest);(path/'manifest.json').write_bytes(raw)
        return {'path':str(path),'manifest_sha256':sha256(raw),'records':count,
                'elapsed_seconds':time.monotonic()-started,'bytes':database.stat().st_size}
    except BaseException:
        # Preserve the partial directory; absence of the completion manifest is
        # explicit incomplete state, never a cache hit or successful zero result.
        raise


@dataclass(frozen=True)
class SourceSelection:
    selection: dict
    records: tuple
    selected_sources: tuple
    execution: dict
    structural: dict
    exclusion_root: Path


def select_vcf(vcf_path, *, scope, concordance, sample, fetch_reference, reference_mapping, exclusion_root,
               classification, evidence_origin, index=None, expected_index_sha256=None,
               maximum_selected=100000, deadline_seconds=3600,pid_phase_contract=None):
    """Streaming and indexed consumers share source QC and normalization kernels."""
    prepared=prepare_intervals(scope)
    bound=binding(scope,concordance,sample,reference_mapping,classification,evidence_origin,pid_phase_contract,prepared=prepared)
    with ExclusionWriter(exclusion_root,binding=bound,source_records=concordance.total_records) as exclusions:
        return _select_vcf(vcf_path,scope=scope,concordance=concordance,sample=sample,
            fetch_reference=fetch_reference,classification=classification,evidence_origin=evidence_origin,
            index=index,expected_index_sha256=expected_index_sha256,maximum_selected=maximum_selected,
            deadline_seconds=deadline_seconds,bound=bound,exclusions=exclusions,pid_phase_contract=pid_phase_contract,
            prepared=prepared)


def _select_vcf(vcf_path, *, scope, concordance, sample, fetch_reference,
                classification, evidence_origin, index, expected_index_sha256,
                maximum_selected, deadline_seconds, bound, exclusions,pid_phase_contract,prepared):
    started=time.monotonic()
    require(deadline_seconds is None or (type(deadline_seconds) in (int,float)
        and math.isfinite(deadline_seconds) and deadline_seconds>0), 'invalid selection deadline')
    deadline=math.inf if deadline_seconds is None else started+deadline_seconds
    from genosapiens.track2_structural import observe, component, source_context
    regions=prepared.rows
    require(type(maximum_selected) is int and maximum_selected>0)
    require((index is None)==(expected_index_sha256 is None))
    selected_rows=[];kept=[];seen=0;classes=Counter();observations=[];accounting=Counter()
    def retain_structural(rows):
        require(len(observations)+len(rows)<=maximum_selected,
            'structural selection incomplete: observation budget exceeded')
        require(time.monotonic()<=deadline,'structural selection incomplete: deadline exceeded')
        observations.extend(rows)
    def consume(record):
        nonlocal seen
        seen+=1
        require(time.monotonic()<=deadline,'source selection incomplete: deadline exceeded')
        if record.filter_value != 'PASS':
            exclusions.append(filter_exclusion(record))
            if index is None:accounting.update(account_record(record,None,(),(),bound))
            return
        n=normalize(record,bound,fetch_reference)
        require(all(a.normalized_allele is not None or not SMALL.fullmatch(a.alternate)
                    or a.alternate==record.reference for a in n.alleles),
                'source normalization coverage is incomplete')
        rows=selected(record,n,prepared.by_contig,bound)
        if index is None:
            structural_rows=observe(record,structural_context,prepared.structural_by_contig,bound)
            retain_structural(structural_rows)
            accounting.update(account_record(record,n,rows,structural_rows,bound))
        if rows:
            require(len(selected_rows)+len(rows)<=maximum_selected,'source selection incomplete: record budget exceeded')
            selected_rows.extend(rows);kept.append((record,n))
    if index is None:
        with iter_vcf_qc_records(vcf_path,concordance_report=concordance,
                max_header_bytes=concordance.read_limits.max_header_bytes,max_record_bytes=concordance.read_limits.max_record_bytes,
                pid_phase_contract=pid_phase_contract) as stream:
            require(sample in stream.header.sample_names,'selected sample is absent')
            header=stream.header
            structural_context=source_context(header)
            for record in stream:
                classes.update(str(kind) for kind in record.variant_classes)
                consume(record)
        strategy='streaming';index_sha=None
    else:
        path=Path(index);signature(path/'manifest.json')
        raw=read_bounded_bytes(path/'manifest.json',maximum_bytes=128*1024*1024)
        require(sha256(raw)==expected_index_sha256)
        manifest=json.loads(raw);database=path/'selection.sqlite'
        require(manifest['schema']==INDEX_SCHEMA and manifest['binding']==bound
                and signature(vcf_path)==manifest['source_signature']
                and signature(database)==manifest['index_signature'])
        require(manifest['record_count']==concordance.total_records)
        source_digest,_=_file_sha256(vcf_path)
        require(source_digest==bound['source_sha256'],'Indexed source authentication differs.')
        require(_file_identity(database)[0]==manifest['index_sha256'],'Selection index authentication differs.')
        classes.update(manifest['source_alternate_class_counts'])
        require(set(manifest['source_accounting'])==set(ACCOUNTING))
        accounting.update(manifest['source_accounting'])
        require(manifest['filter_exclusions']['binding']==exclusions.binding)
        require(manifest['filter_exclusions']['source_record_count']==manifest['record_count']
                and manifest['filter_exclusions']['source_alternate_count']==sum(classes.values()))
        for row in iter_exclusions(path/'filter-exclusions',manifest['filter_exclusions']):
            exclusions.append(row)
        header=decode(VcfQcStreamHeader,manifest['header'])
        require(header.input_sha256==bound['source_sha256'] and sample in header.sample_names)
        header_context=prepare_header(header);format_cache=FormatLayoutCache()
        before=signature(database)
        with closing(sqlite3.connect(database.resolve().as_uri()+'?mode=ro',uri=True)) as db:
            require(db.execute('SELECT identity FROM completion').fetchall()==[(sha256(canonical(bound)),)])
            for (raw_observations,) in db.execute('SELECT observations FROM structural ORDER BY ordinal'):
                retain_structural(json.loads(raw_observations))
            ids=set()
            for chrom,start,end,_ in regions:
                ids.update(r[0] for r in db.execute('SELECT ordinal FROM spans WHERE chrom=? AND start<? AND end>?',
                                                   (chrom,end,start)))
                require(len(ids)<=maximum_selected,'source selection incomplete: record budget exceeded')
            for ordinal in sorted(ids):
                row=db.execute('SELECT raw FROM records WHERE ordinal=?',(ordinal,)).fetchone()
                require(row is not None)
                raw_line=row[0]
                consume(_parse_stream_record(raw_line.rstrip('\r\n'),record_number=ordinal,header=header,
                    raw_line_sha256=sha256(raw_line.encode('ascii')),raw_line=raw_line,
                    prepared_header=header_context,format_cache=format_cache))
        require(signature(database)==before and signature(vcf_path)==manifest['source_signature'])
        strategy='indexed';index_sha=expected_index_sha256
    require(time.monotonic()<=deadline,'source selection incomplete: deadline exceeded')
    # Preserve distinct source ALT identities even if normalization collapses
    # representations; genotype construction owns biological deduplication.
    selected_rows.sort(key=lambda r:(r['source_record_id'],r['allele_number']))
    members=[{k:r[k] for k in ('allele_id','source_record_id','source_allele_id')} for r in selected_rows]
    structural=component(observations,header,bound)
    exclusion_artifact=exclusions.finish(source_records=seen if index is None else manifest['record_count'],
        source_alternates=sum(classes.values()))
    require(sum(accounting.values())==sum(classes.values())
        and accounting['sequence_scoped']==len(members)
        and accounting['quality_excluded']==exclusion_artifact['excluded_alternate_count'],
        'Source ALT accounting does not reconcile.')
    from genosapiens.track2_vcf_evidence import evidence
    selection={'schema':'genosapiens.track2-source-selection/v4','classification':classification,
        'vcf_evidence':evidence(bound,strategy),
        'evidence_origin':evidence_origin,'source_sha256':bound['source_sha256'],'sample':sample,
        'reference_sha256':bound['reference_sha256'],'index_sha256':index_sha,
        'vcf_policy_sha256':VCF_POLICY_SHA256,
        'scope_sha256':bound['scope_sha256'],'subset_sha256':sha256(canonical(members)),
        'structural_sha256':sha256(canonical(structural)),
        'strategy':strategy,'selected_alleles':members,'coverage':{'state':'complete_within_declared_scope',
        'selected_allele_count':len(members),'source_record_count':concordance.total_records,
        'filter_policy':POLICY,'filter_exclusions':exclusion_artifact,
        'filter_excluded_record_count':exclusion_artifact['excluded_record_count'],
        'filter_excluded_alternate_count':exclusion_artifact['excluded_alternate_count'],
        'source_alternate_class_counts':dict(sorted(classes.items())),
        'source_accounting':{'unit':'source_ALT_occurrences',**{k:accounting[k] for k in ACCOUNTING}},
        'unsupported_classes':['SV','CNV','repeat','symbolic'],
        'limitations':['Selection covers source-event or normalized reference spans of carried/unknown small alleles.',
            'Structural calls have separate scoped screening. Structural genotype and mechanism interpretation remain unassessed.',
            'Unsupported classes and outside-scope partners remain unassessed. This analysis does not establish whole-genome completeness.']}}
    return SourceSelection(selection,tuple(kept),tuple(selected_rows),
        {'elapsed_seconds':time.monotonic()-started,'records_interpreted_for_selection':seen,
         'expensive_annotation_records':0,'binding':bound},structural,exclusions.root)
